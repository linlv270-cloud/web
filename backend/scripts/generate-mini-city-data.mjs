import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "lib", "china-area-data.json");
const targetPath = path.join(root, "miniprogram", "utils", "china-city-data.ts");
const areas = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const directCities = new Set([
  "北京市",
  "天津市",
  "上海市",
  "重庆市",
  "香港特别行政区",
  "澳门特别行政区",
]);

const provinceEntries = Object.entries(areas["86"] || {}).map(([code, name]) => {
  const cities = directCities.has(name)
    ? [{ code, name }]
    : Object.entries(areas[code] || {}).map(([cityCode, cityName]) => ({ code: cityCode, name: cityName }));
  return { code, name, cities: cities.length ? cities : [{ code, name }] };
});

const output = `// Generated by scripts/generate-mini-city-data.mjs. Do not edit manually.\n` +
  `export type CityEntry = { code: string; name: string };\n` +
  `export type ProvinceEntry = CityEntry & { cities: CityEntry[] };\n\n` +
  `export const provinceEntries: ProvinceEntry[] = ${JSON.stringify(provinceEntries, null, 2)};\n`;

fs.writeFileSync(targetPath, output);
console.log(`Generated ${provinceEntries.length} provinces at ${targetPath}`);
